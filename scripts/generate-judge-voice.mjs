import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const root = resolve(import.meta.dirname, '..');
const outputDir = join(root, 'public/assets/audio/lighthouse-town/judge');
const sourceOutput = join(root, 'src/audio/judgeVoiceAssets.ts');
const manifestOutput = join(outputDir, 'manifest.json');
const residents = ['你（ME）', '林澜', '沈砚', '唐果', '墨七', '苏萤', '白露', '顾潮', '阿满', '玄微先生'];
const lines = [
  '各位居民，欢迎来到灯塔镇狼人杀圆桌。法官将全程主持，请听从阶段提示。',
  '请九位玩家按座位号入座。上帝观察者可以看到全局，但不会替玩家行动。',
  '身份已经分发。狼人、预言家、女巫、猎人和平民请确认自己的身份；现在准备入夜。',
  '天黑请闭眼。狼人请睁眼，商量今晚的目标。',
  '狼人请闭眼。预言家请睁眼并选择查验对象。',
  '预言家请闭眼。女巫请睁眼并决定是否用药。',
  '天亮了。现在公布昨夜结果。',
  '天亮了。昨夜平安，无人离场。',
  '现在按座位顺序依次发言。',
  '发言结束，现在开始投票。',
  '出现平票，请候选人依次补充发言。',
  '补充发言结束，现在重新投票。',
  '猎人可以选择发动技能，也可以放弃。',
  '本局结束，现在公布身份与结果。',
  ...residents.map((name) => `现在请 ${name} 发言。`),
  ...residents.map((name) => `天亮了。昨夜${name}离场，已安全前往观众席。`),
  ...residents.flatMap((first) => residents
    .filter((second) => second !== first)
    .map((second) => `天亮了。昨夜${first}、${second}离场，已安全前往观众席。`)),
];
const uniqueLines = [...new Set(lines)];

function run(command, args) {
  const result = spawnSync(command, args, { encoding: 'utf8' });
  if (result.status !== 0) throw new Error(`${command} failed: ${result.stderr || result.stdout}`);
}

function sha256(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

function render() {
  mkdirSync(outputDir, { recursive: true });
  const scratch = mkdtempSync(join(tmpdir(), 'lighthouse-judge-'));
  const tracks = [];
  try {
    uniqueLines.forEach((text, index) => {
      const id = `judge-${String(index + 1).padStart(3, '0')}`;
      const aiff = join(scratch, `${id}.aiff`);
      const filename = `${id}.m4a`;
      const output = join(outputDir, filename);
      run('/usr/bin/say', ['-v', 'Tingting', '-r', '185', '-o', aiff, text]);
      run('/usr/bin/afconvert', [aiff, output, '-f', 'm4af', '-d', 'aac', '-b', '64000']);
      tracks.push({
        id,
        text,
        src: `/ai-town/assets/audio/lighthouse-town/judge/${filename}`,
        voice: 'Tingting (zh_CN, local macOS voice)',
        aiGenerated: true,
        sha256: sha256(output),
      });
      console.log(`${id}: ${text}`);
    });
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
  writeFileSync(manifestOutput, `${JSON.stringify({ version: 1, tracks }, null, 2)}\n`);
  const entries = tracks.map(({ text, src }) => `  ${JSON.stringify(text)}: ${JSON.stringify(src)},`).join('\n');
  writeFileSync(sourceOutput,
    `// Generated by scripts/generate-judge-voice.mjs. Do not edit by hand.\n` +
    `export const JUDGE_VOICE_ASSETS: Readonly<Record<string, string>> = {\n${entries}\n};\n`,
  );
}

function validate() {
  if (!existsSync(manifestOutput) || !existsSync(sourceOutput)) throw new Error('Judge voice assets are missing.');
  const manifest = JSON.parse(readFileSync(manifestOutput, 'utf8'));
  if (manifest.tracks.length !== uniqueLines.length) throw new Error('Judge voice manifest is incomplete.');
  for (const track of manifest.tracks) {
    const path = join(outputDir, track.src.split('/').at(-1));
    if (!existsSync(path) || readFileSync(path).length < 4096) throw new Error(`${track.id} is invalid.`);
    if (sha256(path) !== track.sha256) throw new Error(`${track.id} checksum mismatch.`);
  }
  console.log(`${manifest.tracks.length} bundled judge voice clips are valid.`);
}

if (process.argv.includes('--validate')) validate();
else render();
